-- Helper: current application user id.
create or replace function public.current_app_user_id()
returns bigint
language sql
stable
security definer
set search_path = public
as $$
  select id from public.app_users where auth_user_id = auth.uid() limit 1;
$$;

-- Helper: current school.
create or replace function public.current_school_id()
returns bigint
language sql
stable
security definer
set search_path = public
as $$
  select school_id from public.app_users where auth_user_id = auth.uid() limit 1;
$$;

-- Helper: role permission check.
create or replace function public.has_app_permission(p_permission text)
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1
    from public.app_users u
    join public.roles r on r.id=u.role_id
    where u.auth_user_id=auth.uid()
      and u.status='Active'
      and (
        r.permissions @> jsonb_build_array('*')
        or r.permissions @> jsonb_build_array(p_permission)
      )
  );
$$;

revoke all on function public.current_app_user_id() from public;
revoke all on function public.current_school_id() from public;
revoke all on function public.has_app_permission(text) from public;
grant execute on function public.current_app_user_id() to authenticated;
grant execute on function public.current_school_id() to authenticated;
grant execute on function public.has_app_permission(text) to authenticated;

